#!/usr/bin/env python3
"""Generates ember/runtime/ember_math_consts.h: the constants used by ember_math.h.

Everything is computed with exact integer and rational arithmetic and written as C99 hex
floats, so no constant depends on a typed-in decimal. Run `python3 tests/gen_math_consts.py`
to regenerate; tests/test_math.py fails if the checked-in file differs from this output.
"""
import math
import sys
from fractions import Fraction
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "ember" / "runtime" / "ember_math_consts.h"
BITS = 700   # working precision, far beyond what any double constant needs


def atan_inv(n):
    """atan(1/n) as a Fraction accurate to well beyond BITS bits (Machin-style series)."""
    one = 1 << (BITS + 32)
    total, term, k, sign = 0, one // n, 0, 1
    while term:
        total += sign * (term // (2 * k + 1))
        term //= n * n
        k, sign = k + 1, -sign
    return Fraction(total, one)


PI = 16 * atan_inv(5) - 4 * atan_inv(239)


def ln2_value():
    # ln 2 = 2 * atanh(1/3) = 2 * sum 1/((2k+1) 3^(2k+1))
    one = 1 << (BITS + 32)
    total, term, k = 0, one // 3, 0
    while term:
        total += term // (2 * k + 1)
        term //= 9
        k += 1
    return Fraction(2 * total, one)


LN2 = ln2_value()


def hexf(x):
    return float(x).hex()


def top_bits(x, nbits):
    """x rounded toward zero to nbits significant bits, as an exact Fraction."""
    if x == 0:
        return Fraction(0)
    e = 0
    while x >= 2 ** (e + 1):
        e += 1
    while x < 2 ** e:
        e -= 1
    scale = Fraction(2) ** (nbits - 1 - e)
    return Fraction(int(x * scale)) / scale


def split(x, parts, nbits):
    out, rest = [], x
    for _ in range(parts):
        p = top_bits(rest, nbits)
        out.append(p)
        rest -= p
    return out, rest


def fact(n):
    return math.factorial(n)


def lines():
    out = []

    def const(name, value):
        out.append(f"#define {name} {hexf(value)}")

    def table(name, values):
        out.append(f"static const double {name}[{len(values)}] = {{")
        for v in values:
            out.append(f"    {hexf(v)},")
        out.append("};")

    out.append("/* Generated by tests/gen_math_consts.py. Do not edit. */")
    out.append("#ifndef EMBER_MATH_CONSTS_H")
    out.append("#define EMBER_MATH_CONSTS_H")
    out.append("")
    out.append("/* pi/2 in three 33-bit pieces, so that n * piece is exact for n < 2^20, plus a")
    out.append("   double for what is left. */")
    pieces, rest = split(PI / 2, 3, 33)
    for i, p in enumerate(pieces, 1):
        const(f"EM_PIO2_{i}", p)
    const("EM_PIO2_4", rest)
    const("EM_INV_PIO2", 2 / PI)
    out.append("")
    out.append("/* pi, pi/2, pi/4 and 3*pi/4 as a double plus a correction. */")
    for name, v in (("PI", PI), ("PIO2", PI / 2), ("PIO4", PI / 4)):
        hi = Fraction(float(v))
        const(f"EM_{name}_HI", hi)
        const(f"EM_{name}_LO", v - hi)
    const("EM_3PIO4", 3 * PI / 4)
    out.append("")
    out.append("/* ln 2: the high part has 42 bits, so k * EM_LN2_HI is exact for |k| < 2^11. */")
    ln2_hi = top_bits(LN2, 42)
    const("EM_LN2_HI", ln2_hi)
    const("EM_LN2_LO", LN2 - ln2_hi)
    const("EM_INV_LN2", 1 / LN2)
    out.append("")
    out.append("/* tan(pi/8): where atan switches to its second range reduction. */")
    # tan(pi/8) = sqrt(2) - 1; sqrt via integer arithmetic
    s2 = Fraction(math.isqrt(2 << (2 * BITS)), 1 << BITS)
    const("EM_TAN_PIO8", s2 - 1)
    const("EM_SQRT2", s2)
    out.append("")
    out.append("/* sin r = r + r*z*(S[0] + z*(S[1] + ...)), z = r*r; S[k] = (-1)^(k+1) / (2k+3)! */")
    table("EM_SIN_C", [Fraction((-1) ** (k + 1), fact(2 * k + 3)) for k in range(10)])
    out.append("/* cos r = (1 - z/2) + z*z*(C[0] + z*(C[1] + ...)); C[k] = (-1)^k / (2k+4)! */")
    table("EM_COS_C", [Fraction((-1) ** k, fact(2 * k + 4)) for k in range(10)])
    out.append("/* exp r = 1 + (r + r*r*(E[0] + r*(E[1] + ...))); E[k] = 1 / (k+2)! */")
    table("EM_EXP_C", [Fraction(1, fact(k + 2)) for k in range(14)])
    out.append("/* atan t = t + t*z*(A[0] + z*(A[1] + ...)), z = t*t; A[k] = (-1)^(k+1) / (2k+3) */")
    table("EM_ATAN_C", [Fraction((-1) ** (k + 1), 2 * k + 3) for k in range(24)])
    out.append("/* ln(1+f) = 2*(s + s*z*(L[0] + z*(L[1] + ...))), s = f/(2+f), z = s*s; L[k] = 1/(2k+3) */")
    table("EM_LN_C", [Fraction(1, 2 * k + 3) for k in range(12)])
    out.append("")
    out.append("#endif")
    return out


def main():
    text = "\n".join(lines()) + "\n"
    if "--check" in sys.argv:
        return 0 if OUT.exists() and OUT.read_text() == text else 1
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
