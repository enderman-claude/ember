"""Writes tests/num_cases.inc: expected results for tests/num_test.c.

The expected values are computed independently of ember_num.h:
  f64      Python's repr (the shortest round-trip form, the same rules as Ember's printing)
  f32      the fewest digits that, read back as a single, give the same value
  bigfloat exact rational arithmetic with fractions.Fraction, printed the way Ember prints

Run `python3 tests/gen_num_cases.py` after changing the cases. test_floats.py checks that the
committed file is current.
"""
import random
import struct
import sys
from fractions import Fraction
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from ember.floats import literal_bits  # noqa: E402  (exact decimal -> f32 bits)


def f64_repr(bits):
    return repr(struct.unpack("<d", struct.pack("<Q", bits))[0])


def f32_value(bits):
    return struct.unpack("<f", struct.pack("<I", bits))[0]


def f32_text(bits):
    """Shortest decimal that reads back as this single, in Ember's plain/scientific style."""
    if bits & 0x7FFFFFFF == 0:
        return "-0.0" if bits >> 31 else "0.0"
    value = abs(f32_value(bits))
    neg = bits >> 31
    for d in range(1, 10):
        text = f"{value:.{d - 1}e}"
        if literal_bits(text, "f32") == (bits & 0x7FFFFFFF):
            mant, exp = text.split("e")
            digits = mant.replace(".", "").rstrip("0") or "0"
            x = int(exp)
            break
    else:
        raise AssertionError("no round-tripping decimal")
    if -4 <= x < 16:
        if x >= 0:
            ip = digits[:x + 1].ljust(x + 1, "0")
            fp = digits[x + 1:] or "0"
            out = f"{ip}.{fp}"
        else:
            out = "0." + "0" * (-x - 1) + digits
    else:
        out = digits[0] + ("." + digits[1:] if len(digits) > 1 else "")
        out += "e" + ("-" if x < 0 else "+") + f"{abs(x):02d}"
    return ("-" if neg else "") + out


def big_text(q: Fraction):
    """Exact decimal when it terminates, otherwise 40 digits and '...'. Sign first."""
    if q == 0:
        return "0"
    sign = "-" if q < 0 else ""
    q = abs(q)
    den = q.denominator
    a = b = 0
    while den % 2 == 0:
        den //= 2
        a += 1
    while den % 5 == 0:
        den //= 5
        b += 1
    if den == 1:
        k = max(a, b)
        scaled = q.numerator * 10 ** k // q.denominator
        s = str(scaled).rjust(k + 1, "0")
        out = s if k == 0 else s[:-k] + "." + s[-k:]
    else:
        ip = q.numerator // q.denominator
        frac = q - ip
        digits = (frac * 10 ** 40).numerator // (frac * 10 ** 40).denominator
        out = f"{ip}." + str(digits).rjust(40, "0") + "..."
    return sign + out


def c_str(s):
    return '"' + s + '"'


def main():
    rng = random.Random(20260704)
    f64_cases = [0x0000000000000000, 0x8000000000000000, 0x3FF0000000000000, 0x4000000000000000,
                 0x3FB999999999999A, 0x3FD3333333333333, 0x0000000000000001, 0x7FEFFFFFFFFFFFFF,
                 0x7FF0000000000000, 0xFFF0000000000000, 0x40C81C8000000000, 0x3E45798EE2308C3A]
    for _ in range(3000):
        exp = rng.randint(1, 2046)                      # normal numbers only
        f64_cases.append((rng.randint(0, 1) << 63) | (exp << 52) | rng.getrandbits(52))
    f64_cases += [rng.getrandbits(64) & 0x800FFFFFFFFFFFFF for _ in range(200)]   # subnormals

    f32_cases = [0x3DCCCCCD, 0x3EAAAAAB, 0x4B800000, 0x00000001, 0x7F7FFFFF, 0x3F800000]
    for _ in range(3000):                               # finite, normal numbers
        exp = rng.randint(1, 254)
        f32_cases.append((rng.randint(0, 1) << 31) | (exp << 23) | rng.getrandbits(23))

    big_cases = []
    ops = [("+", lambda a, b: a + b), ("-", lambda a, b: a - b),
           ("*", lambda a, b: a * b), ("/", lambda a, b: a / b)]

    def rand_rational():
        num = rng.randint(-10 ** rng.randint(0, 25), 10 ** rng.randint(0, 25))
        den = rng.randint(1, 10 ** rng.randint(0, 20))
        return Fraction(num, den)

    for _ in range(600):
        a, b = rand_rational(), rand_rational()
        if b == 0:
            continue
        sym, fn = ops[rng.randint(0, 3)]
        big_cases.append((a, b, sym, fn(a, b)))
    big_cases += [(Fraction(100, 3), Fraction(3), "*", Fraction(100)),
                  (Fraction(1, 3), Fraction(1, 6), "+", Fraction(1, 2)),
                  (Fraction(2 ** 100), Fraction(1), "+", Fraction(2 ** 100 + 1)),
                  (Fraction(10 ** 30), Fraction(7), "/", Fraction(10 ** 30, 7))]

    lines = [
        "/* Generated by tests/gen_num_cases.py. Do not edit. */",
        "typedef struct { uint64_t bits; const char *text; } f64_case;",
        "typedef struct { uint32_t bits; const char *text; } f32_case;",
        "typedef struct { const char *an, *ad, *bn, *bd; char op; const char *text; } big_case;",
        "static const f64_case F64_CASES[] = {",
    ]
    for bits in f64_cases:
        lines.append(f"    {{0x{bits:016X}ULL, {c_str(f64_repr(bits))}}},")
    lines += ["};", "static const f32_case F32_CASES[] = {"]
    for bits in f32_cases:
        lines.append(f"    {{0x{bits:08X}U, {c_str(f32_text(bits))}}},")
    lines += ["};", "static const big_case BIG_CASES[] = {"]
    for a, b, sym, q in big_cases:
        # Operands are written as sign-prefixed numerator and denominator strings.
        lines.append(f"    {{{c_str(str(a.numerator))}, {c_str(str(a.denominator))}, "
                     f"{c_str(str(b.numerator))}, {c_str(str(b.denominator))}, '{sym}', "
                     f"{c_str(big_text(q))}}},")
    lines += ["};", ""]
    out = ROOT / "tests" / "num_cases.inc"
    out.write_text("\n".join(lines))
    print(f"wrote {out} ({len(f64_cases)} f64, {len(f32_cases)} f32, {len(big_cases)} bigfloat cases)")


if __name__ == "__main__":
    main()
